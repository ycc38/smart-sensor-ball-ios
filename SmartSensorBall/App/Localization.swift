import Foundation

enum AppLanguage: String, CaseIterable, Identifiable {
    case chinese = "zh"
    case english = "en"
    case french = "fr"
    case spanish = "es"
    case german = "de"
    case korean = "ko"
    case thai = "th"

    var id: String { rawValue }

    static var current: AppLanguage {
        let stored = UserDefaults.standard.string(forKey: "app_language")
        return AppLanguage(rawValue: stored ?? "") ?? .chinese
    }

    var displayName: String {
        switch self {
        case .chinese: return "简体中文"
        case .english: return "English"
        case .french: return "Français"
        case .spanish: return "Español"
        case .german: return "Deutsch"
        case .korean: return "한국어"
        case .thai: return "ไทย"
        }
    }

    var legalSuffix: String {
        switch self {
        case .chinese: return "zh"
        case .english: return "en"
        case .french: return "fr"
        case .spanish: return "es"
        case .german: return "de"
        case .korean: return "ko"
        case .thai: return "th"
        }
    }

    var speechLanguageCode: String {
        switch self {
        case .chinese: return "zh-CN"
        case .english: return "en-US"
        case .french: return "fr-FR"
        case .spanish: return "es-ES"
        case .german: return "de-DE"
        case .korean: return "ko-KR"
        case .thai: return "th-TH"
        }
    }

    /// Picks the text for this language. Spanish, German and Korean fall back to English
    /// when no translation is passed, the same way the Android app does.
    func localized(
        _ chinese: String,
        _ english: String,
        fr french: String,
        th thai: String,
        es spanish: String? = nil,
        de german: String? = nil,
        ko korean: String? = nil
    ) -> String {
        switch self {
        case .chinese: return chinese
        case .english: return english
        case .french: return french
        case .thai: return thai
        case .spanish: return spanish ?? english
        case .german: return german ?? english
        case .korean: return korean ?? english
        }
    }

    func save() {
        UserDefaults.standard.set(rawValue, forKey: "app_language")
    }
}

